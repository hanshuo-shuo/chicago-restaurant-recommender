"""HTTP API and web UI with impression-level feedback logging.

Every recommendation response is logged as impressions (request, session, item,
position, model version). Clicks and favorites are accepted only when they
reference a logged impression from the same session and request, so each event
is attributable to the exact model and slot that produced it. These logs live
in their own SQLite store and are never mixed into the historical ratings used
for offline training and evaluation.
"""
from __future__ import annotations

import json
import math
import sqlite3
import sys
import time
import uuid
from datetime import datetime, timezone
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from typing import Any
from urllib.parse import parse_qs, urlsplit

DEFAULT_DB = Path("data/logs/events.sqlite3")
WEB_FILE = Path(__file__).resolve().parent / "static" / "index.html"
MAX_BODY = 16_384
ROUTES = {"/", "/favicon.ico", "/api/health", "/api/info", "/api/search", "/api/catalog", "/api/metrics",
          "/api/online-metrics", "/api/recommend", "/api/events"}
PREFERENCE_KEYS = {"cuisines", "budget", "max_price_level", "open_after_8pm", "seed_item_ids", "exclude_seen",
                   "location", "max_distance_km", "include_closed"}


class BadRequest(ValueError):
    """A safe, actionable validation error for the client."""


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds")


def _session(value: Any) -> str:
    if not isinstance(value, str):
        raise BadRequest("session_id must be an anonymous UUID v4 generated by the client.")
    try:
        parsed = uuid.UUID(value)
    except (ValueError, AttributeError):
        raise BadRequest("session_id must be an anonymous UUID v4.")
    if parsed.version != 4 or str(parsed) != value.lower():
        raise BadRequest("session_id must be a canonical anonymous UUID v4.")
    return str(parsed)


def _unknown_keys(body: dict, allowed: set) -> None:
    unknown = set(body) - allowed
    if unknown:
        raise BadRequest("Unsupported fields: %s." % ", ".join(sorted(unknown)))


def _public_catalog(engine: Any) -> list:
    value = engine.catalog()
    if isinstance(value, list):
        return value
    if isinstance(value, dict):
        for key in ("items", "catalog"):
            if isinstance(value.get(key), list):
                return value[key]
    raise RuntimeError("Engine catalog must return a list of items.")


def _validate_recommend(body: dict, item_ids: set, cuisines: set) -> tuple:
    _unknown_keys(body, {"session_id", "preferences", "model", "k"})
    session_id = _session(body.get("session_id"))
    model = body.get("model", "baseline")
    if model not in ("baseline", "two_tower", "learned", "llm"):
        raise BadRequest("model must be 'baseline', 'two_tower', 'learned' or 'llm'.")
    k = body.get("k", 5)
    if type(k) is not int or not 1 <= k <= 20:
        raise BadRequest("k must be an integer between 1 and 20.")
    preferences = body.get("preferences", {})
    if not isinstance(preferences, dict):
        raise BadRequest("preferences must be a JSON object.")
    _unknown_keys(preferences, PREFERENCE_KEYS)
    preferences = dict(preferences)
    for key, choices, limit in (("cuisines", cuisines, 20), ("seed_item_ids", item_ids, 20)):
        values = preferences.get(key, [])
        if not isinstance(values, list) or len(values) > limit or any(not isinstance(v, str) for v in values):
            raise BadRequest("%s must be a list of up to %d catalog values." % (key, limit))
        invalid = set(values) - choices
        if invalid:
            raise BadRequest("Unknown %s. Refresh /api/catalog and select valid catalog values." % key)
        preferences[key] = list(dict.fromkeys(values))
    budget = preferences.get("budget")
    if budget is not None:
        if type(budget) not in (int, float) or not math.isfinite(budget) or not 0 < budget <= 10_000:
            raise BadRequest("budget must be null or a finite positive number up to 10000.")
        preferences["budget"] = float(budget)
    level = preferences.get("max_price_level")
    if level is not None and (type(level) is not int or not 1 <= level <= 4):
        raise BadRequest("max_price_level must be null or an integer from 1 to 4.")
    for key in ("open_after_8pm", "exclude_seen", "include_closed"):
        if key in preferences and type(preferences[key]) is not bool:
            raise BadRequest("%s must be true or false." % key)
    location = preferences.get("location")
    if location is not None:
        if not isinstance(location, dict) or set(location) != {"latitude", "longitude"} or any(
                type(location[c]) not in (int, float) or not math.isfinite(location[c]) for c in location) or not (
                -90 <= location["latitude"] <= 90 and -180 <= location["longitude"] <= 180):
            raise BadRequest("location must be {\"latitude\": number, \"longitude\": number}.")
        preferences["location"] = {c: float(location[c]) for c in location}
    distance = preferences.get("max_distance_km")
    if distance is not None:
        if type(distance) not in (int, float) or not math.isfinite(distance) or not 0 < distance <= 100:
            raise BadRequest("max_distance_km must be null or a number in (0, 100].")
        if location is None and not preferences.get("seed_item_ids"):
            raise BadRequest("max_distance_km needs a location or at least one seed restaurant.")
        preferences["max_distance_km"] = float(distance)
    return session_id, model, k, preferences


def _init_db(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with sqlite3.connect(str(path), timeout=10) as connection:
        connection.executescript("""
            PRAGMA journal_mode=WAL;
            CREATE TABLE IF NOT EXISTS impressions (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                request_id TEXT NOT NULL,
                session_id TEXT NOT NULL,
                item_id TEXT NOT NULL,
                position INTEGER NOT NULL,
                model TEXT NOT NULL,
                model_version TEXT NOT NULL,
                timestamp TEXT NOT NULL,
                retrieval_score REAL,
                ranking_score REAL,
                distance_km REAL,
                UNIQUE(request_id, session_id, item_id)
            );
            CREATE TABLE IF NOT EXISTS requests (
                request_id TEXT PRIMARY KEY,
                session_id TEXT NOT NULL,
                model TEXT NOT NULL,
                model_version TEXT NOT NULL,
                preferences TEXT NOT NULL,
                timestamp TEXT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS events (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                impression_id INTEGER NOT NULL REFERENCES impressions(id),
                request_id TEXT NOT NULL,
                session_id TEXT NOT NULL,
                item_id TEXT NOT NULL,
                type TEXT NOT NULL CHECK(type IN ('click', 'favorite')),
                position INTEGER NOT NULL,
                model TEXT NOT NULL,
                model_version TEXT NOT NULL,
                timestamp TEXT NOT NULL
            );
            CREATE INDEX IF NOT EXISTS events_impression ON events(impression_id);
            CREATE INDEX IF NOT EXISTS impressions_model ON impressions(model);
        """)
        columns = {row[1] for row in connection.execute("PRAGMA table_info(impressions)")}
        for column in ("retrieval_score", "ranking_score", "distance_km"):  # databases from v1 of the schema
            if column not in columns:
                connection.execute(f"ALTER TABLE impressions ADD COLUMN {column} REAL")


def _online_metrics(connection: sqlite3.Connection) -> list[dict]:
    """Per-model CTR and favorite rate; an impression counts once however many times it is clicked."""
    rows = connection.execute("""
        SELECT i.model, count(*) AS impressions, count(DISTINCT i.request_id) AS requests,
               sum(EXISTS(SELECT 1 FROM events e WHERE e.impression_id = i.id AND e.type = 'click')) AS clicked,
               sum(EXISTS(SELECT 1 FROM events e WHERE e.impression_id = i.id AND e.type = 'favorite')) AS favorited
        FROM impressions i GROUP BY i.model ORDER BY i.model
    """).fetchall()
    return [{"model": model, "requests": requests, "impressions": impressions,
             "clicked_impressions": clicked, "favorited_impressions": favorited,
             "ctr": round(clicked / impressions, 6), "favorite_rate": round(favorited / impressions, 6)}
            for model, impressions, requests, clicked, favorited in rows]


class RecommenderServer(ThreadingHTTPServer):
    daemon_threads = True
    allow_reuse_address = True

    def __init__(self, address: tuple, engine: Any, db_path: Path, access_log: bool = False):
        self.engine = engine
        items = _public_catalog(engine)  # the catalog is static while serving, so validate against sets built once
        self.item_ids = {str(item["item_id"]) for item in items}
        self.cuisines = {str(item.get("cuisine")) for item in items if item.get("cuisine")}
        self.db_path = db_path
        self.access_log = access_log
        super().__init__(address, RequestHandler)


class RequestHandler(BaseHTTPRequestHandler):
    server: RecommenderServer
    server_version = "RestaurantRecs/1.0"

    def log_message(self, format: str, *args: Any) -> None:
        # The default handler logs raw request lines; structured access logs are emitted in _send.
        pass

    def _send(self, status: int, body: Any, content_type: str = "application/json; charset=utf-8") -> None:
        if isinstance(body, bytes):
            encoded = body
        else:
            encoded = json.dumps(body, ensure_ascii=False, allow_nan=False).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(encoded)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("Referrer-Policy", "no-referrer")
        self.send_header("Content-Security-Policy", "default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src 'self' https://fonts.gstatic.com; img-src 'self' data:; connect-src 'self'; frame-ancestors 'none'; base-uri 'none'; form-action 'self'")
        self.end_headers()
        self.wfile.write(encoded)
        if self.server.access_log:
            path = urlsplit(self.path).path
            print(json.dumps({"ts": _now(), "method": self.command, "path": path if path in ROUTES else "<other>",
                              "status": status, "ms": round((time.perf_counter() - self._started) * 1000, 2)}),
                  file=sys.stderr, flush=True)

    def _body(self) -> dict:
        origin = self.headers.get("Origin")
        if origin and urlsplit(origin).netloc != self.headers.get("Host"):
            raise BadRequest("Cross-origin writes are disabled.")
        if self.headers.get("Content-Type", "").split(";", 1)[0].strip() != "application/json":
            raise BadRequest("Send Content-Type: application/json.")
        try:
            length = int(self.headers.get("Content-Length", "0"))
        except ValueError:
            raise BadRequest("Content-Length must be a valid integer.")
        if not 0 < length <= MAX_BODY:
            raise BadRequest("Provide a JSON object smaller than 16 KiB.")
        try:
            body = json.loads(self.rfile.read(length).decode("utf-8"), parse_constant=lambda value: (_ for _ in ()).throw(ValueError(value)))
        except (UnicodeDecodeError, ValueError):
            raise BadRequest("Body must contain valid JSON with finite numbers.")
        if not isinstance(body, dict):
            raise BadRequest("Body must be a JSON object.")
        return body

    def do_GET(self) -> None:
        self._started = time.perf_counter()
        path = urlsplit(self.path).path
        try:
            if path == "/":
                self._send(200, WEB_FILE.read_bytes(), "text/html; charset=utf-8")
            elif path == "/favicon.ico":
                self._send(204, b"")
            elif path == "/api/catalog":
                self._send(200, self.server.engine.catalog())
            elif path == "/api/info":
                self._send(200, self.server.engine.info())
            elif path == "/api/search":
                text = parse_qs(urlsplit(self.path).query).get("q", [""])[0][:64]
                self._send(200, {"results": self.server.engine.search(text)})
            elif path == "/api/metrics":
                self._send(200, self.server.engine.metrics())
            elif path == "/api/online-metrics":
                with sqlite3.connect(str(self.server.db_path)) as connection:
                    self._send(200, {"by_model": _online_metrics(connection)})
            elif path == "/api/health":
                with sqlite3.connect(str(self.server.db_path)) as connection:
                    impressions = connection.execute("SELECT count(*) FROM impressions").fetchone()[0]
                    events = dict(connection.execute("SELECT type, count(*) FROM events GROUP BY type").fetchall())
                self._send(200, {"status": "ok", "model_version": getattr(self.server.engine, "model_version", None),
                                 "log_counts": {"impressions": impressions, "clicks": events.get("click", 0), "favorites": events.get("favorite", 0)}})
            else:
                self._send(404, {"error": "Route not found."})
        except Exception:
            self._send(500, {"error": "Model artifacts could not be loaded. Run prepare/train and check the server log."})

    def do_POST(self) -> None:
        self._started = time.perf_counter()
        path = urlsplit(self.path).path
        try:
            if path not in ("/api/recommend", "/api/events"):
                self._send(404, {"error": "Route not found."})
                return
            body = self._body()
            if path == "/api/recommend":
                self._recommend(body)
            else:
                self._event(body)
        except BadRequest as exc:
            self._send(400, {"error": str(exc)})
        except (ValueError, KeyError):
            self._send(400, {"error": "The model could not use these preferences. Refresh the catalog or rebuild the artifacts."})
        except Exception:
            self._send(500, {"error": "Recommendation failed. Check that model artifacts exist and retry."})

    def _recommend(self, body: dict) -> None:
        session_id, model, k, preferences = _validate_recommend(body, self.server.item_ids, self.server.cuisines)
        result = self.server.engine.recommend(preferences=preferences, model=model, k=k)
        if not isinstance(result, dict) or not isinstance(result.get("recommendations"), list):
            raise RuntimeError("Engine recommendation contract failed.")
        rows = result["recommendations"]
        known = self.server.item_ids
        returned_ids = [row.get("item_id") for row in rows]
        if len(rows) > k or len(set(returned_ids)) != len(rows) or any(item_id not in known for item_id in returned_ids):
            raise RuntimeError("Engine returned invalid item identities.")
        request_id = str(uuid.uuid4())
        applied_model = str(result.get("model", model))
        model_version = str(result.get("model_version", model))
        timestamp = _now()
        with sqlite3.connect(str(self.server.db_path), timeout=10) as connection:
            connection.execute("INSERT INTO requests (request_id, session_id, model, model_version, preferences, timestamp) VALUES (?, ?, ?, ?, ?, ?)", (request_id, session_id, applied_model, model_version, json.dumps(preferences, sort_keys=True), timestamp))
            connection.executemany("INSERT INTO impressions (request_id, session_id, item_id, position, model, model_version, timestamp, retrieval_score, ranking_score, distance_km) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)", [(request_id, session_id, row["item_id"], position, applied_model, model_version, timestamp, row.get("retrieval_score"), row.get("ranking_score"), row.get("distance_km")) for position, row in enumerate(rows, 1)])
        result = dict(result)
        result["request_id"] = request_id
        result["impressions_logged"] = len(rows)
        result["latency_ms"] = round((time.perf_counter() - self._started) * 1000, 2)
        self._send(200, result)

    def _event(self, body: dict) -> None:
        _unknown_keys(body, {"session_id", "request_id", "item_id", "type"})
        session_id = _session(body.get("session_id"))
        event_type = body.get("type")
        if event_type not in ("click", "favorite"):
            raise BadRequest("type must be 'click' or 'favorite'.")
        request_id, item_id = body.get("request_id"), body.get("item_id")
        if not isinstance(request_id, str) or not isinstance(item_id, str) or len(request_id) > 80 or len(item_id) > 128:
            raise BadRequest("request_id and item_id must come from a previous recommendation.")
        with sqlite3.connect(str(self.server.db_path), timeout=10) as connection:
            row = connection.execute("SELECT id, position, model, model_version FROM impressions WHERE request_id=? AND session_id=? AND item_id=?", (request_id, session_id, item_id)).fetchone()
            if row is None:
                raise BadRequest("No matching impression for this session, request and item. Get recommendations first.")
            impression_id, position, model, model_version = row
            cursor = connection.execute("INSERT INTO events (impression_id, request_id, session_id, item_id, type, position, model, model_version, timestamp) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)", (impression_id, request_id, session_id, item_id, event_type, position, model, model_version, _now()))
            event_id = cursor.lastrowid
        self._send(201, {"ok": True, "event_id": event_id, "type": event_type, "position": position, "model_version": model_version})


def create_server(engine: Any, host: str = "127.0.0.1", port: int = 8766, db_path: Any = DEFAULT_DB,
                  access_log: bool = False) -> RecommenderServer:
    """Create an unstarted server; port=0 is useful for isolated HTTP tests."""
    path = Path(db_path)
    _init_db(path)
    return RecommenderServer((host, port), engine, path, access_log)


def serve(engine: Any, host: str = "127.0.0.1", port: int = 8766, db_path: Any = DEFAULT_DB) -> None:
    server = create_server(engine, host, port, db_path, access_log=True)
    print("Serving %s on http://%s:%s (Ctrl+C to stop)" % ((engine.model_version,) + server.server_address[:2]), flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()
